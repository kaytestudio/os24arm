#!/usr/bin/env python3
"""Generate keymap_us.h: a self-contained US keymap in XKB text format, for
xkb_keymap_new_from_string() when no xkeyboard-config tree is installed.
Key codes are Linux evdev codes + 8 (what wlroots and libinput use)."""
import sys

keys = {  # evdev code: (level1, level2)
    1: ("Escape",), 14: ("BackSpace",), 15: ("Tab", "ISO_Left_Tab"), 28: ("Return",),
    57: ("space",), 58: ("Caps_Lock",), 29: ("Control_L",), 97: ("Control_R",),
    42: ("Shift_L",), 54: ("Shift_R",), 56: ("Alt_L",), 100: ("Alt_R",),
    125: ("Super_L",), 126: ("Super_R",), 127: ("Menu",),
    12: ("minus", "underscore"), 13: ("equal", "plus"), 26: ("bracketleft", "braceleft"),
    27: ("bracketright", "braceright"), 39: ("semicolon", "colon"), 40: ("apostrophe", "quotedbl"),
    41: ("grave", "asciitilde"), 43: ("backslash", "bar"), 51: ("comma", "less"),
    52: ("period", "greater"), 53: ("slash", "question"),
    102: ("Home",), 103: ("Up",), 104: ("Prior",), 105: ("Left",), 106: ("Right",),
    107: ("End",), 108: ("Down",), 109: ("Next",), 110: ("Insert",), 111: ("Delete",),
    99: ("Print",), 119: ("Pause",), 70: ("Scroll_Lock",), 69: ("Num_Lock",),
    55: ("KP_Multiply",), 74: ("KP_Subtract",), 78: ("KP_Add",), 96: ("KP_Enter",), 98: ("KP_Divide",),
    71: ("KP_7",), 72: ("KP_8",), 73: ("KP_9",), 75: ("KP_4",), 76: ("KP_5",), 77: ("KP_6",),
    79: ("KP_1",), 80: ("KP_2",), 81: ("KP_3",), 82: ("KP_0",), 83: ("KP_Decimal",),
}
for i, (a, b) in enumerate(zip("1234567890", "!@#$%^&*()")):
    names = {"!": "exclam", "@": "at", "#": "numbersign", "$": "dollar", "%": "percent",
             "^": "asciicircum", "&": "ampersand", "*": "asterisk", "(": "parenleft", ")": "parenright"}
    keys[2 + i] = (a, names[b])
for row, start in (("qwertyuiop", 16), ("asdfghjkl", 30), ("zxcvbnm", 44)):
    for i, c in enumerate(row):
        keys[start + i] = (c, c.upper())
for i in range(10):
    keys[59 + i] = ("F%d" % (i + 1),)
keys[87], keys[88] = ("F11",), ("F12",)

letters = {k for k, v in keys.items() if len(v) == 2 and len(v[0]) == 1 and v[0].isalpha()}
out = ['xkb_keymap {', ' xkb_keycodes "os2" {', '  minimum = 8; maximum = 255;']
out += ['  <K%d> = %d;' % (c + 8, c + 8) for c in sorted(keys)]
out += [' };', ' xkb_types "os2" {', '  virtual_modifiers NumLock, Alt, Super;',
        '  type "ONE_LEVEL" { modifiers = none; level_name[Level1] = "Any"; };',
        '  type "TWO_LEVEL" { modifiers = Shift; map[Shift] = Level2;'
        ' level_name[Level1] = "Base"; level_name[Level2] = "Shift"; };',
        '  type "ALPHABETIC" { modifiers = Shift + Lock; map[Shift] = Level2; map[Lock] = Level2;'
        ' level_name[Level1] = "Base"; level_name[Level2] = "Caps"; };',
        ' };', ' xkb_compat "os2" {', '  virtual_modifiers NumLock, Alt, Super;']
for sym, act in (("Shift_L", "SetMods(modifiers = Shift)"), ("Shift_R", "SetMods(modifiers = Shift)"),
                 ("Control_L", "SetMods(modifiers = Control)"), ("Control_R", "SetMods(modifiers = Control)"),
                 ("Alt_L", "SetMods(modifiers = Mod1)"), ("Alt_R", "SetMods(modifiers = Mod1)"),
                 ("Super_L", "SetMods(modifiers = Mod4)"), ("Super_R", "SetMods(modifiers = Mod4)"),
                 ("Caps_Lock", "LockMods(modifiers = Lock)")):
    out.append('  interpret %s { action = %s; };' % (sym, act))
out += [' };', ' xkb_symbols "os2" {', '  name[Group1] = "English (US)";']
for c in sorted(keys):
    v = keys[c]
    t = ' type = "ALPHABETIC",' if c in letters else ''
    out.append('  key <K%d> {%s [ %s ] };' % (c + 8, t, ", ".join(v)))
out += ['  modifier_map Shift { <K50>, <K62> };', '  modifier_map Lock { <K66> };',
        '  modifier_map Control { <K37>, <K105> };', '  modifier_map Mod1 { <K64>, <K108> };',
        '  modifier_map Mod4 { <K133>, <K134> };', ' };', '};']
text = "\n".join(out) + "\n"
with open(sys.argv[1] if len(sys.argv) > 1 else "keymap_us.h", "w") as f:
    f.write("/* Generated by userland/wlr-os2/gen-keymap.py - do not edit. */\n")
    f.write("static const char os2_keymap_us[] =\n")
    for line in text.splitlines():
        f.write('    "%s\\n"\n' % line.replace("\\", "\\\\").replace('"', '\\"'))
    f.write("    ;\n")
